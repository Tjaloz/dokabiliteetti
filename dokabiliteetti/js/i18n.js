export var nykyinenKieli = localStorage.getItem(KIELI_AVAIN) || "fi";
if (!KAANNOKSET[nykyinenKieli]) nykyinenKieli = "fi";

export function t(avain, muuttujat) {
  var sanasto = KAANNOKSET[nykyinenKieli] || KAANNOKSET.fi;
  var teksti = sanasto[avain] != null ? sanasto[avain] : (KAANNOKSET.fi[avain] || avain);
  if (muuttujat) {
    Object.keys(muuttujat).forEach(function (k) {
      teksti = teksti.split("{" + k + "}").join(muuttujat[k]);
    });
  }
  return teksti;
}

var kuuntelijat = [];
export function kielenVaihtuessa(fn) {
  kuuntelijat.push(fn);
}

export function soveltaaStaattinenKaannos() {
  document.documentElement.lang = nykyinenKieli;
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n]"), function (el) {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-placeholder]"), function (el) {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  Array.prototype.forEach.call(document.querySelectorAll("[data-i18n-aria-label]"), function (el) {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
}

export function asetaKieli(kieli) {
  if (!KAANNOKSET[kieli]) return;
  nykyinenKieli = kieli;
  try { localStorage.setItem(KIELI_AVAIN, kieli); } catch (e) { /* ei kriittinen */ }
  soveltaaStaattinenKaannos();
  Array.prototype.forEach.call(document.querySelectorAll(".kieli-btn"), function (btn) {
    btn.classList.toggle("active", btn.getAttribute("data-kieli") === kieli);
  });
  kuuntelijat.forEach(function (fn) {
    try { fn(); } catch (e) { console.error("Kielenvaihtokuuntelija epäonnistui", e); }
  });
}
